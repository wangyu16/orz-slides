/**
 * Writes src/version.ts from package.json, so the isomorphic modules know the
 * shell version without reading files (FC-18 law 2: no environment reads).
 * Run by `prebuild` and `pretest`; tests/base.test.ts checks it is in sync.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync('package.json', 'utf8')) as { version: string };
const out = `// Generated by scripts/sync-version.ts from package.json — do not edit.\n\n/** The orz-slides version: the shell version written into every assembled file. */\nexport const VERSION = ${JSON.stringify(version)};\n`;
let current = '';
try {
  current = readFileSync('src/version.ts', 'utf8');
} catch {
  /* first run */
}
if (current !== out) writeFileSync('src/version.ts', out, 'utf8');
